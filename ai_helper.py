def ask_gigachat(text):
    """
    Интеллектуальный классификатор обращений.
    Разделяет ввод на 4 типа по ТЗ: Потенциальная опасность, Информационный вопрос, 
    Обычная неисправность, Недостаточно данных.
    """
    if not text:
        return {
            "type": "Недостаточно данных",
            "need_ticket": False,
            "title": "Пустой запрос",
            "category": "Общее",
            "answer": "Вы ничего не ввели. Пожалуйста, опишите проблему или задайте вопрос."
        }

    text_lower = text.lower()
    
    # 1. АВТОМАТИЧЕСКИЙ ПЕРЕХВАТ ОПАСНЫХ СИТУАЦИЙ (Критическое требование безопасности ТЗ!)
    danger_triggers = [
        "искрит", "дым", "запах гари", "ударило током", "пожар", "горит", 
        "проводка", "затопило", "коротит", "оголенные провода", "плавится"
    ]
    for trigger in danger_triggers:
        if trigger in text_lower:
            return {
                "type": "Потенциальная опасность",
                "need_ticket": False,
                "title": "КРИТИЧЕСКАЯ УГРОЗА БЕЗОПАСНОСТИ",
                "category": "Электрика и Безопасность",
                "answer": (
                    "ВНИМАНИЕ! Категорически запрещено выполнять самостоятельный ремонт, вскрывать приборы "
                    "или трогать проводку! Не приближайтесь к оборудованию. Немедленно покиньте опасную зону "
                    "и срочно сообщите преподавателю, ответственному сотруднику колледжа или экстренным службам!"
                )
            }

    # 2. ПОИСК СОВПАДЕНИЙ В ОФИЦИАЛЬНОЙ БАЗЕ ЗНАНИЙ
    if "проектор" in text_lower or "подключить ноутбук" in text_lower or "экран" in text_lower:
        kb_match = OFFICIAL_KB["проектор"]
    elif "принтер" in text_lower or "печать" in text_lower or "печатает" in text_lower or "картридж" in text_lower:
        kb_match = OFFICIAL_KB["принтер"]
    elif "компьютер" in text_lower or "пк" in text_lower or "монитор" in text_lower or "завис" in text_lower:
        kb_match = OFFICIAL_KB["компьютер"]
    elif "регламент" in text_lower or "инструкция" in text_lower or "сломалось" in text_lower:
        kb_match = OFFICIAL_KB["неисправность"]
    else:
        kb_match = None

    if kb_match and any(x in text_lower for x in ["как", "правила", "инструкция", "где", "почему", "проверить"]):
        return {
            "type": "Информационный вопрос",
            "need_ticket": True,
            "title": kb_match["title"],
            "category": kb_match["category"],
            "answer": f"Найдена официальная база знаний: {kb_match['answer']}"
        }

    # 3. ПРОВЕРКА НА НЕДОСТАТОК ДАННЫХ
    if len(text_lower.strip()) < 15 or text_lower.strip() in ["у меня проблема", "помогите", "не работает", "сломалось"]:
        return {
            "type": "Недостаточно данных",
            "need_ticket": False,
            "title": "Необходимы уточнения",
            "category": "Общее",
            "answer": "Недостаточно информации для классификации. Пожалуйста, укажите конкретнее: какое оборудование неисправно и что именно произошло?"
        }

    # 4. АВТОМАТИЧЕСКОЕ ОПРЕДЕЛЕНИЕ КАТЕГОРИИ ДЛЯ ОБЫЧНЫХ НЕИСПРАВНОСТЕЙ
    category = "Хозяйственные вопросы"
    if any(x in text_lower for x in ["проектор", "компьютер", "пк", "монитор", "ноутбук", "принтер", "интернет", "печать"]):
        category = "Оборудование и ИТ"
    elif any(x in text_lower for x in ["парта", "стул", "дверь", "ручка", "окно", "шкаф", "мебель"]):
        category = "Имущество и мебель"
    elif any(x in text_lower for x in ["свет", "лампа", "розетка", "выключатель"]):
        category = "Электрика и освещение"

    ai_title = text[:45] + "..." if len(text) > 45 else text

    return {
        "type": "Обычная неисправность",
        "need_ticket": True,
        "title": ai_title,
        "category": category,
        "answer": "Ваше обращение распознано как техническая неисправность. Вы можете отправить созданный ИИ черновик заявки в панель УПК."
    }